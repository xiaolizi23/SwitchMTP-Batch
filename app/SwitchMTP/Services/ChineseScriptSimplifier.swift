// Traditional Chinese -> Simplified Chinese, applied only for display.
//
// The Chinese catalogue we can reach is the Hong Kong one, so a normal retail
// library is named in Traditional script. Mainland players and consoles use
// Simplified, and for a few Nintendo franchises the mainland name is not a
// character-by-character conversion at all (瑪利歐賽車 -> 马力欧卡丁车, not
// 玛利欧赛车). The table in `Resources/T2S.json` therefore has two layers:
//
//   * phrases  — multi-character, checked longest-first, holding the franchise
//                names that need real translation on top of OpenCC's phrase map
//   * chars    — OpenCC's TSCharacters single-character map
//
// Both come from OpenCC (Apache-2.0), regenerated by `scripts/build-t2s.py`.
// Conversion is local: no network, and it never rewrites the stored catalogue.

import Foundation

enum ChineseScriptSimplifier {

    private struct Phrase {
        let source: [Character]
        let replacement: String
    }

    private static let phrases: [Phrase] = loadPhrases()
    private static let chars: [Character: Character] = loadChars()

    /// Converts Traditional text to Simplified. Text that is already Simplified
    /// passes through untouched, ASCII and punctuation included.
    static func simplify(_ text: String) -> String {
        guard !text.isEmpty, !phrases.isEmpty || !chars.isEmpty else { return text }

        let input = Array(text)
        var output = String()
        output.reserveCapacity(text.count)

        var index = 0
        while index < input.count {
            var replaced = false
            for phrase in phrases {
                let count = phrase.source.count
                if index + count > input.count { continue }
                if Array(input[index..<(index + count)]) == phrase.source {
                    output.append(contentsOf: phrase.replacement)
                    index += count
                    replaced = true
                    break
                }
            }
            if replaced { continue }
            output.append(chars[input[index]] ?? input[index])
            index += 1
        }
        return output
    }

    // MARK: - Table loading

    private static func loadTable() -> [String: Any]? {
        guard let url = Bundle.main.url(forResource: "T2S", withExtension: "json"),
              let data = try? Data(contentsOf: url),
              let object = try? JSONSerialization.jsonObject(with: data) as? [String: Any]
        else { return nil }
        return object
    }

    private static func loadPhrases() -> [Phrase] {
        guard let table = loadTable(),
              let raw = table["phrases"] as? [[String]]
        else { return [] }
        // The file is already sorted by descending key length; keep that order
        // so the first hit is always the longest one.
        return raw.compactMap { pair in
            guard pair.count == 2, !pair[0].isEmpty else { return nil }
            return Phrase(source: Array(pair[0]), replacement: pair[1])
        }
    }

    private static func loadChars() -> [Character: Character] {
        guard let table = loadTable(),
              let raw = table["chars"] as? [String: String]
        else { return [:] }
        var map: [Character: Character] = [:]
        map.reserveCapacity(raw.count)
        for (key, value) in raw {
            guard let from = key.first, key.count == 1, let to = value.first else { continue }
            map[from] = to
        }
        return map
    }
}
